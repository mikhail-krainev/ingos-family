MVP_CONTINGENCY = (0.10, "допущение", "Резерв на непредвиденные расходы")


def mvp_budget():
    rows = []
    for cat, item, qty, unit, months, payroll, tag, note in MVP_ITEMS:
        mult = g("payroll_mult") if payroll else 1.0
        total = qty * unit * months * mult
        rows.append({
            "Категория": cat, "Статья": item, "Кол-во": qty, "Цена за ед., руб": round(unit, 2),
            "Месяцев": months, "Взносы": "да" if payroll else "нет", "Итого, руб": round(total),
            "Метка": tag, "Комментарий": note,
        })
    df = pd.DataFrame(rows)
    subtotal = df["Итого, руб"].sum()
    overhead = round(df.loc[df["Взносы"] == "да", "Итого, руб"].sum() * g("overhead_share"))
    df.loc[len(df)] = {"Категория": "Накладные", "Статья": "Накладные 10% от ФОТ", "Кол-во": 1, "Цена за ед., руб": overhead,
                       "Месяцев": 1, "Взносы": "нет", "Итого, руб": overhead, "Метка": "допущение",
                       "Комментарий": "Рабочие места, HR, бухгалтерия"}
    reserve = round((subtotal + overhead) * MVP_CONTINGENCY[0])
    df.loc[len(df)] = {"Категория": "Резерв", "Статья": "Резерв 10%", "Кол-во": 1, "Цена за ед., руб": reserve,
                       "Месяцев": 1, "Взносы": "нет", "Итого, руб": reserve, "Метка": MVP_CONTINGENCY[1],
                       "Комментарий": MVP_CONTINGENCY[2]}
    return df


