def sensitivity(mvp_total):
    key_metric = "NPV до налога за 60 мес, руб"
    base_npv = metrics(simulate(params_for({}), mvp_total))[key_metric]
    rows = []
    for key, label in SENS_KEYS:
        res = {}
        for shift in (-0.25, 0.25):
            p = params_for({})
            p[key] = p[key] * (1 + shift)
            if key == "price_basic":
                p["price_ext"] = p["price_ext"] * (1 + shift)
                p["b2b_price"] = p["b2b_price"] * (1 + shift)
            res[shift] = metrics(simulate(p, mvp_total))[key_metric]
        rows.append({"Параметр": label, "-25%": res[-0.25], "+25%": res[0.25], "Размах": abs(res[0.25] - res[-0.25])})
    return base_npv, pd.DataFrame(rows).sort_values("Размах", ascending=False)


