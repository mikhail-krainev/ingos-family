COLORS = {"Пессимистичный": "#C0392B", "Базовый": "#1E3FD8", "Оптимистичный": "#2E8B57", "Версия 1": "#888888"}


def ru(x, digits=1):
    return f"{x:.{digits}f}".replace(".", ",")


def charts(mvp_df, scen, v1_df, tornado_base, tornado, npv_dist):
    plt.rcParams.update({"font.family": "Times New Roman", "font.size": 12})

    cat = mvp_df.groupby("Категория")["Итого, руб"].sum().sort_values()
    fig, ax = plt.subplots(figsize=(9, 4.8))
    ax.barh(cat.index, cat.values / 1e6, color="#1E3FD8")
    for i, v in enumerate(cat.values):
        ax.text(v / 1e6 + 0.03, i, ru(v / 1e6, 2), va="center")
    ax.set_xlabel("млн руб.")
    ax.set_title(f"Бюджет MVP: {ru(mvp_df['Итого, руб'].sum() / 1e6, 2)} млн руб. при лимите 5 млн")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(CHARTS / "Бюджет_MVP_по_категориям.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 4.8))
    for name, df in scen.items():
        ax.plot(df["Месяц"], df["Накопленный результат"] / 1e6, label=name, color=COLORS[name], lw=2)
    ax.plot(v1_df["Месяц"], v1_df["Накопленный результат"] / 1e6, label="Версия 1 без триажа", color=COLORS["Версия 1"], lw=1.5, ls="--")
    ax.axhline(0, color="#888", lw=1)
    ax.axvspan(0.5, 3.5, color="#B8F02A", alpha=0.25, label="MVP")
    ax.set_xlabel("Месяц")
    ax.set_ylabel("млн руб.")
    ax.set_title("Накопленный операционный результат")
    ax.legend(frameon=False, fontsize=9)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(CHARTS / "Накопленный_результат_по_сценариям.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 4.5))
    for name, df in scen.items():
        ax.plot(df["Месяц"], df["Всего семей"], label=name, color=COLORS[name], lw=2)
    ax.set_xlabel("Месяц")
    ax.set_ylabel("Активных семей")
    ax.set_title("Активные семьи (B2C и B2B2C)")
    ax.legend(frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(CHARTS / "Активные_семьи_по_сценариям.png", dpi=160)
    plt.close(fig)

    t = tornado.iloc[::-1]
    fig, ax = plt.subplots(figsize=(9, 5))
    y = np.arange(len(t))
    ax.barh(y, (t["-25%"] - tornado_base) / 1e6, color="#8FA3F0", label="Параметр -25%")
    ax.barh(y, (t["+25%"] - tornado_base) / 1e6, color="#1E3FD8", label="Параметр +25%")
    ax.set_yticks(y, t["Параметр"])
    ax.axvline(0, color="#333", lw=1)
    ax.set_xlabel("Изменение NPV, млн руб.")
    ax.set_title(f"Чувствительность NPV за 60 мес (база {ru(tornado_base / 1e6)} млн руб.)")
    ax.legend(frameon=False, loc="lower right")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(CHARTS / "Чувствительность_NPV.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 4.5))
    ax.hist(npv_dist / 1e6, bins=60, color="#1E3FD8", alpha=0.85)
    ax.axvline(0, color="#C0392B", lw=1.5)
    ax.set_xlabel("NPV за 60 месяцев, млн руб.")
    ax.set_ylabel("Число прогонов")
    ax.set_title(f"Монте-Карло, 5000 прогонов: NPV за 60 мес > 0 в {ru((npv_dist > 0).mean() * 100, 0)}% случаев")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(CHARTS / "Монте_Карло_NPV.png", dpi=160)
    plt.close(fig)


