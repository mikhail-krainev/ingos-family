def params_for(overrides):
    p = {k: v[0] for k, v in BASE.items()}
    p.update(overrides)
    return p


def load_per_coord(p):
    """Семей на координатора: базовых и расширенных, с учетом подмены."""
    if "fixed_load" in p:
        base_load, ext_w = p["fixed_load"]
        return base_load / COVERAGE_MULT[0], base_load / ext_w / COVERAGE_MULT[0]
    cap = PRODUCTIVE_MIN[0] / COVERAGE_MULT[0]
    return cap / (minutes("Базовый") * p["time_mult"]), cap / (minutes("Расширенный") * p["time_mult"])


def simulate(p, mvp_cost_total, include_cross=False):
    """Помесячная модель. Возвращает DataFrame."""
    rows = []
    b2c = 0.0
    b2c_new_prev = 0.0
    b2b = 0.0
    b2b_cohorts = []
    mkt = 0.0
    coords_prev = 3
    mvp_monthly = mvp_cost_total / MVP_MONTHS
    vat = g("vat")
    load_b, load_e = load_per_coord(p)
    pm = g("payroll_mult")
    for m in range(1, MONTHS + 1):
        year = (m - 1) // 12
        sal_k = (1 + g("salary_index_y")) ** year
        price_k = (1 + g("price_index_y")) ** year
        arpu_list = (p["price_basic"] * (1 - p["share_ext"]) + p["price_ext"] * p["share_ext"]) * price_k
        arpu_gross = arpu_list * (1 - veteran_discount())
        cross = 0.0

        if m <= MVP_MONTHS:
            fam = p["mvp_families"][m]
            paying = fam * p["mvp_paying_share"]
            rev_sub = paying * arpu_gross / (1 + vat)
            benefits = paying * (arpu_list - arpu_gross) / (1 + vat)
            rev_comm = fam * p["partner_spend"] * p["partner_commission"] / (1 + vat)
            row = {
                "Месяц": m, "Фаза": "MVP", "Семьи B2C": fam, "Семьи B2B2C": 0, "Всего семей": fam,
                "Новые B2C": fam - p["mvp_families"].get(m - 1, 0), "Координаторы": 3 if m > 1 else 0,
                "Выручка подписка": rev_sub, "Выручка B2B2C": 0.0, "Выручка комиссия": rev_comm,
                "Маркетинг": 0.0, "Партнерский канал фонда": 0.0, "Координаторы ФОТ": 0.0, "Переменные": 0.0, "Команда": 0.0,
                "Прочие постоянные": 0.0, "Инвестиции": 0.0, "Бюджет MVP": mvp_monthly,
            }
            row["Выручка"] = rev_sub + rev_comm
            row["Расходы"] = mvp_monthly
            b2c = fam
            b2c_new_prev = row["Новые B2C"]
        else:
            # Маркетинг: сначала дешевые внутренние каналы, остаток во внешние
            mkt = p["mkt_start"] if m == MVP_MONTHS + 1 else min(mkt * (1 + p["mkt_growth_m"]), p["mkt_cap"])
            int_new = min(p["int_cap"], mkt / p["int_cac"])
            ext_new = max(0.0, mkt - int_new * p["int_cac"]) / p["ext_cac"]
            vet_new = p["vet_new"] if m >= p["vet_start_month"] else 0.0
            vet_cost = vet_new * p["vet_cac"]
            new_b2c = int_new + ext_new + vet_new

            # Отток: новички уходят чаще
            b2c = (b2c - b2c_new_prev) * (1 - p["churn_b2c"]) + b2c_new_prev * (1 - p["churn_first"]) + new_b2c
            b2c_new_prev = new_b2c

            # B2B2C с разгоном активации внутри клиента
            if m >= p["b2b_start_month"]:
                b2b_cohorts.append((m, p["b2b_clients_per_month"] * p["b2b_employees"] * p["b2b_activation"]))
            add = sum(size / p["b2b_ramp_months"] for start, size in b2b_cohorts if m - start < p["b2b_ramp_months"])
            b2b = b2b * (1 - p["churn_b2b"]) + add

            fam = b2c + b2b
            fam_ext = b2c * p["share_ext"]
            fam_basic = b2c * (1 - p["share_ext"]) + b2b
            coords = max(3, math.ceil(fam_basic / load_b + fam_ext / load_e))
            supervisors = math.ceil(coords / p["supervisor_ratio"])

            rev_sub = b2c * arpu_gross / (1 + vat)
            benefits = b2c * (arpu_list - arpu_gross) / (1 + vat)
            rev_b2b = b2b * p["b2b_price"] * price_k / (1 + vat)
            rev_comm = fam * p["partner_spend"] * p["partner_commission"] / (1 + vat)

            coord_pay = (coords * p["coord_salary"] + supervisors * p["supervisor_salary"]) * sal_k * pm
            hires = max(0, coords - coords_prev) + coords * p["coord_turnover_y"] / 12
            onboarding = hires * p["onboarding_cost"] * sal_k
            seats = (coords + supervisors) * p["seat_cost"]
            variable = fam * (p["telemed_per_family"] + p["telecom_per_family"]) + \
                (b2c * arpu_gross + b2b * p["b2b_price"] * price_k) * g("acquiring")
            team = sum(fte * sal for fte, sal, start in p["team"].values() if m >= start) * sal_k * pm
            overhead = (team + coord_pay) * g("overhead_share")
            other_fixed = p["hosting_base"] + p["hosting_per_1000"] * fam / 1000 + p["legal_entity_m"]
            capex = p["capex"].get(m, 0)
            coords_prev = coords
            cross = fam * p["cross_rate_m"] * p["cross_margin"]

            row = {
                "Месяц": m, "Фаза": "Масштабирование", "Семьи B2C": b2c, "Семьи B2B2C": b2b,
                "Всего семей": fam, "Новые B2C": new_b2c, "Координаторы": coords,
                "Выручка подписка": rev_sub, "Выручка B2B2C": rev_b2b, "Выручка комиссия": rev_comm,
                "Маркетинг": mkt, "Партнерский канал фонда": vet_cost, "Координаторы ФОТ": coord_pay + onboarding, "Переменные": variable + seats,
                "Команда": team, "Прочие постоянные": overhead + other_fixed, "Инвестиции": capex, "Бюджет MVP": 0.0,
            }
            row["Выручка"] = rev_sub + rev_b2b + rev_comm
            row["Расходы"] = mkt + vet_cost + coord_pay + onboarding + variable + seats + team + overhead + other_fixed + capex

        row["Кросс-продажи (эффект группы)"] = cross
        row["Льготы ветеранам (недополученная выручка)"] = benefits
        row["Операционный результат"] = row["Выручка"] - row["Расходы"] + (cross if include_cross else 0.0)
        rows.append(row)

    df = pd.DataFrame(rows)
    df["Накопленный результат"] = df["Операционный результат"].cumsum()
    df["Налог на прибыль"] = income_tax(df)
    df["Денежный поток после налога"] = df["Операционный результат"] - df["Налог на прибыль"]
    return df


def income_tax(df):
    """Налог по годам с переносом убытков (лимит 50% базы). Платим в последнем месяце года."""
    tax = np.zeros(len(df))
    carry = 0.0
    for y in range(MONTHS // 12):
        sl = slice(12 * y, 12 * (y + 1))
        profit = float(df["Операционный результат"].iloc[sl].sum())
        if profit <= 0:
            carry += -profit
            continue
        used = min(carry, profit * g("loss_carry_limit"))
        carry -= used
        tax[12 * (y + 1) - 1] = (profit - used) * g("profit_tax")
    return tax


def npv(series):
    r_m = (1 + g("discount_rate_y")) ** (1 / 12) - 1
    t = np.arange(1, len(series) + 1)
    return float((np.asarray(series) / (1 + r_m) ** t).sum())


def metrics(df):
    cum = df["Накопленный результат"].values
    op = df["Операционный результат"].values
    be_month = next((i + 1 for i in range(MVP_MONTHS, MONTHS) if all(op[j] > 0 for j in range(i, MONTHS))), None)
    payback = next((i + 1 for i in range(MONTHS) if all(cum[j] > 0 for j in range(i, MONTHS))), None)
    y = lambda k: df.iloc[12 * k:12 * (k + 1)]
    at = df["Денежный поток после налога"].values
    return {
        "NPV до налога за 36 мес, руб": round(npv(op[:SHORT])),
        "NPV после налога за 36 мес, руб": round(npv(at[:SHORT])),
        "NPV до налога за 60 мес, руб": round(npv(op)),
        "NPV после налога за 60 мес, руб": round(npv(at)),
        "Пиковая потребность в деньгах, руб": round(float(-cum.min()) if cum.min() < 0 else 0.0),
        "Месяц операционной безубыточности": be_month,
        "Месяц окупаемости (накопленный > 0)": payback,
        "Семей на конец 36 мес": round(float(df["Всего семей"].iloc[SHORT - 1])),
        "Семей на конец 60 мес": round(float(df["Всего семей"].iloc[-1])),
        "Координаторов на конец 60 мес": int(df["Координаторы"].iloc[-1]),
        **{f"Выручка год {k + 1}, руб": round(float(y(k)["Выручка"].sum())) for k in range(MONTHS // 12)},
        **{f"Результат год {k + 1}, руб": round(float(y(k)["Операционный результат"].sum())) for k in range(MONTHS // 12)},
        "Кросс-продажи за 60 мес (эффект группы), руб": round(float(df["Кросс-продажи (эффект группы)"].sum())),
        "Льготы ветеранам за 60 мес (недополученная выручка), руб": round(float(df["Льготы ветеранам (недополученная выручка)"].sum())),
    }


def unit_economics(p):
    """Юнит-экономика устоявшейся B2C-семьи (год 1, без индексации)."""
    vat = g("vat")
    pm = g("payroll_mult")
    arpu_list = p["price_basic"] * (1 - p["share_ext"]) + p["price_ext"] * p["share_ext"]
    arpu_gross = arpu_list * (1 - veteran_discount())
    arpu_net = arpu_gross / (1 + vat)
    comm = p["partner_spend"] * p["partner_commission"] / (1 + vat)
    load_b, load_e = load_per_coord(p)
    coord_units = (1 - p["share_ext"]) / load_b + p["share_ext"] / load_e  # доля координатора на семью
    per_coord = (p["coord_salary"] * pm * (1 + g("overhead_share"))
                 + p["supervisor_salary"] * pm * (1 + g("overhead_share")) / p["supervisor_ratio"]
                 + p["seat_cost"] * (1 + 1 / p["supervisor_ratio"])
                 + p["onboarding_cost"] * p["coord_turnover_y"] / 12)
    coord = per_coord * coord_units
    variable = p["telemed_per_family"] + p["telecom_per_family"] + arpu_gross * g("acquiring") + p["hosting_per_1000"] / 1000
    contrib = arpu_net + comm - coord - variable
    # Средний срок жизни с учетом оттока первого месяца
    life = 1 + (1 - p["churn_first"]) / p["churn_b2c"]
    cac_blend = (p["int_cap"] * p["int_cac"] + p["mkt_cap"] - p["int_cap"] * p["int_cac"]) / \
        (p["int_cap"] + (p["mkt_cap"] - p["int_cap"] * p["int_cac"]) / p["ext_cac"])
    ltv = contrib * life
    return {
        "Чек по прейскуранту с НДС, руб/мес": round(arpu_list),
        "Средняя скидка по льготам ветеранам, %": round(veteran_discount() * 100, 1),
        "ARPU с НДС, руб/мес": round(arpu_gross),
        "ARPU без НДС, руб/мес": round(arpu_net),
        "Комиссия партнеров без НДС, руб/мес": round(comm),
        "Семей на координатора: Базовый": round(load_b),
        "Семей на координатора: Расширенный": round(load_e),
        "Координатор, супервизия, накладные на семью, руб/мес": round(coord),
        "Прочие переменные на семью, руб/мес": round(variable),
        "Маржинальный доход на семью, руб/мес": round(contrib),
        "Маржинальность, %": round(contrib / (arpu_net + comm) * 100, 1),
        "Средний срок жизни, мес": round(life, 1),
        "LTV, руб": round(ltv),
        "CAC при полном бюджете (смесь каналов), руб": round(cac_blend),
        "LTV/CAC": round(ltv / cac_blend, 2),
        "Окупаемость CAC, мес": round(cac_blend / contrib, 1) if contrib > 0 else None,
    }


