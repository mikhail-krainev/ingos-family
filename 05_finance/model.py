def main():
    mvp_df = mvp_budget()
    mvp_total = float(mvp_df["Итого, руб"].sum())
    assert mvp_total <= MVP_LIMIT, f"Бюджет MVP {mvp_total:,.0f} превышает лимит"

    scen = {name: simulate(params_for(ov), mvp_total) for name, ov in SCENARIOS.items()}
    scen_metrics = {name: metrics(df) for name, df in scen.items()}
    scen_cross = {name: metrics(simulate(params_for(ov), mvp_total, include_cross=True))["NPV до налога за 60 мес, руб"]
                  for name, ov in SCENARIOS.items()}
    ue = {name: unit_economics(params_for(ov)) for name, ov in SCENARIOS.items()}
    v1_p = params_for(V1_MANUAL)
    v1_df = simulate(v1_p, mvp_total)
    v1 = {"Метрики": metrics(v1_df), "Юнит-экономика": unit_economics(v1_p)}

    base_p = params_for({})
    arpu_gross = (base_p["price_basic"] * (1 - base_p["share_ext"]) + base_p["price_ext"] * base_p["share_ext"]) \
        * (1 - veteran_discount())
    market = market_sizing(arpu_gross, scen_metrics["Базовый"]["Семей на конец 60 мес"])

    tornado_base, tornado = sensitivity(mvp_total)
    npv_dist, mc = monte_carlo(mvp_total)
    charts(mvp_df, scen, v1_df, tornado_base, tornado, npv_dist)

    results = {
        "Бюджет MVP, руб": round(mvp_total),
        "Запас до лимита 5 млн, руб": round(MVP_LIMIT - mvp_total),
        "Бюджет MVP по категориям": mvp_df.groupby("Категория")["Итого, руб"].sum().round().astype(int).to_dict(),
        "Выручка за MVP (базовый), руб": round(float(scen["Базовый"]["Выручка"].iloc[:MVP_MONTHS].sum())),
        "Минуты координатора на семью": {k: round(minutes(k), 1) for k in TIME_BUDGET},
        "Льготы ветеранам": {
            "Доля семей B2C с льготой, %": round(veteran_share() * 100, 1),
            "Средняя скидка с подписки B2C, %": round(veteran_discount() * 100, 1),
            "Категории": {c: {"Доля семей, %": round(sh * 100, 1), "Скидка, %": round(d * 100)}
                          for c, sh, d, *_ in VETERAN_BENEFITS},
        },
        "Сценарии": scen_metrics,
        "NPV до налога с учетом кросс-продаж группы": scen_cross,
        "Юнит-экономика": ue,
        "Версия 1 без триажа (для сравнения)": v1,
        "Рынок": market,
        "Монте-Карло": mc,
        "Чувствительность (топ-3 по размаху NPV)": tornado["Параметр"].head(3).tolist(),
    }
    (OUT / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")

    from build_xlsx import build
    build(OUT / "Финансовая_модель_ИНГОССЕМЬЯ.xlsx", tornado_base, tornado, mc)

    print(json.dumps(results, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
