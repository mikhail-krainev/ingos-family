def monte_carlo(mvp_total, n=5000, seed=42):
    rng = np.random.default_rng(seed)
    out = []
    for _ in range(n):
        p = params_for({k: rng.triangular(*v) for k, v in MC_DIST.items()})
        m = metrics(simulate(p, mvp_total))
        out.append((m["NPV до налога за 60 мес, руб"], m["Месяц окупаемости (накопленный > 0)"],
                    m["Пиковая потребность в деньгах, руб"], m["NPV до налога за 36 мес, руб"]))
    npv_arr = np.array([o[0] for o in out])
    npv36 = np.array([o[3] for o in out])
    peak = np.array([o[2] for o in out])
    paid = [o[1] for o in out if o[1] is not None]
    return npv_arr, {
        "Прогонов": n,
        "Вероятность NPV(36 мес) > 0, %": round(float((npv36 > 0).mean() * 100), 1),
        "Вероятность NPV(60 мес) > 0, %": round(float((npv_arr > 0).mean() * 100), 1),
        "NPV(60) P5, руб": round(float(np.percentile(npv_arr, 5))),
        "NPV(60) P50, руб": round(float(np.percentile(npv_arr, 50))),
        "NPV(60) P95, руб": round(float(np.percentile(npv_arr, 95))),
        "Пиковая потребность P50, руб": round(float(np.percentile(peak, 50))),
        "Пиковая потребность P95, руб": round(float(np.percentile(peak, 95))),
        "Доля прогонов с окупаемостью за 60 мес, %": round(len(paid) / n * 100, 1),
        "Медианный месяц окупаемости (среди окупившихся)": int(np.median(paid)) if paid else None,
    }


